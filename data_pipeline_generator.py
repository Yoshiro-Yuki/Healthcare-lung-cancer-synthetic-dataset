"""Parallel pipeline that generates clean and messy lung-cancer datasets.

This script builds the synthetic dataset in parallel and produces two versions
of it:

    1. Clean: the data exactly as the Healthcare generator produces it.
    2. Messy: the same rows after DirtyDataInjector has added nulls, typos,
       and impossible values.

Rows are split into chunks, and each chunk is generated by its own worker with
its own random seed. Every batch is written to a per-chunk CSV file in
cleaned_folder and messy_folder. Polars then scans each folder lazily
and streams it into one Parquet file, so the full dataset never has to fit in
memory.

All data is entirely synthetic and must not be used for clinical decisions.

Typical usage example:

    python data_pipeline_generator.py
"""
        

# --- Imports ---------------------------------------------------------------
import glob
import os
import psutil
import time
from faker import Faker  # Random source for the provider
from joblib import Parallel, delayed
import numpy as np  # Global seed for reproducibility
import pandas as pd  # Batch DataFrames and CSV writing
import polars as pl  # Lazy CSV scan and Parquet sink

from clean_to_messy import DirtyDataInjector  # Dirty-data step
from synthetic_healthcare_dataset import Healthcare  # Data generator
from data_cleaning import LungCancerCleaner
from mem_tracker import MemoryTracker as mt

# --- Configuration ---------------------------------------------------------
CLEAN_DIR = "cleaned_folder"  # Per-chunk clean CSV files
MESSY_DIR = "messy_folder"  # Per-chunk messy CSV files
CLEAN_PARQUET = "cleaned_data.parquet"  # Final clean output
MESSY_PARQUET = "messy_data.parquet"  # Final messy output

MIN_CHUNK_ROWS = 10  # Healthcare needs >= 10 rows


def prepare_folders():
    """Creates the output folders and removes CSV files from earlier runs.

    Old file-N.csv files would otherwise be picked up by the *.csv glob
    when the number of chunks changes between runs.
    """
    for folder in (CLEAN_DIR, MESSY_DIR):
        os.makedirs(folder, exist_ok=True)
        for stale_file in glob.glob(f"{folder}/*.csv"):
            os.remove(stale_file)


def generate_data(n, seed):
    """Generates one chunk of data and writes its clean and messy CSV files.

    The clean batch is saved first, then corrupted as a copy, so the messy data
    never leaks back into the clean file. Each batch uses its own injector seed
    (seed * 1000 + batch_index) so batches do not share the same noise.

    Args:
      n: Number of rows in this chunk.
      seed: Seed for this chunk. It also sets the first patient ID number, so
        every chunk gets its own non-overlapping IDs.

    Raises:
      ValueError: If n is below MIN_CHUNK_ROWS. The generator would
        otherwise compute a batch size of 0 and loop forever.
    """
    if n < MIN_CHUNK_ROWS:
        raise ValueError(f"n must be at least {MIN_CHUNK_ROWS}, got {n}")

    faker = Faker()
    Faker.seed(seed)
    np.random.seed(seed)
    hc = Healthcare(
        generator=faker, dataset_length=n, start_id=1000001 * (seed + 1)
    )

    messy_path = f"{MESSY_DIR}/file-{seed}.csv"
    clean_path = f"{CLEAN_DIR}/file-{seed}.csv"

    for batch_index, batch in enumerate(hc):
        first = batch_index == 0  # Only the first batch has a header
        mode = "w" if first else "a"

        raw_df = pd.DataFrame(batch)

        # corrupt() works on a copy, so clean_df is left untouched.
        injector = DirtyDataInjector(seed=seed * 1000 + batch_index)
        messy_df = injector.corrupt(raw_df)
        messy_df.to_csv(messy_path, index=False, mode=mode, header=first)

        # clean the corrupted file
        cleaner = LungCancerCleaner()
        cleaned_df = cleaner.clean(messy_df)
        cleaned_df.to_csv(clean_path, index=False, mode=mode, header=first)



def convert_to_parquet(folder, output_path, read_as_text):
    """Streams every CSV file in a folder into one Parquet file.

    Nothing is loaded into memory: Polars scans the files lazily and writes them
    out in chunks.

    Args:
      folder: Folder that contains the CSV files.
      output_path: Path of the Parquet file to write.
      read_as_text: If True, every column is read as text. This is needed for
        the messy data, because a column such as Age mixes numbers with text and
        type guessing would fail partway through the files. If False, types are
        guessed from the first 10,000 rows.

    Returns:
      The number of rows in the Parquet file that was written.
    """
    infer_length = 0 if read_as_text else 10000  # 0 means "all text"
    lazy = pl.scan_csv(f"{folder}/*.csv", infer_schema_length=infer_length)
    lazy.sink_parquet(output_path)

    return pl.scan_parquet(output_path).select(pl.len()).collect().item()


def main(DF_LENGTH=10024574):
    """Runs the full pipeline: generate chunks in parallel, then write Parquet."""

    prepare_folders()

    # Never create chunks smaller than the generator can handle.
    num_chunks = min((os.cpu_count() or 1) * 2, DF_LENGTH // MIN_CHUNK_ROWS)
    df_chunks = [DF_LENGTH // num_chunks] * num_chunks
    df_chunks[-1] = DF_LENGTH - sum(df_chunks[:-1])  # Last chunk takes the rest

    Parallel(n_jobs=-1)(
        delayed(generate_data)(rows, seed) for seed, rows in enumerate(df_chunks)
    )
    

    start_local = time.perf_counter()
    clean_rows = convert_to_parquet(
        CLEAN_DIR, CLEAN_PARQUET, read_as_text=False
    )
    messy_rows = convert_to_parquet(
        MESSY_DIR, MESSY_PARQUET, read_as_text=True
    )

    end_local = time.perf_counter()


    print('='*50)
    print(f'Benchmark for {DF_LENGTH} rows:')
    print(f"clean: {clean_rows} rows saved to {CLEAN_PARQUET}")
    print(f"messy: {messy_rows} rows saved to {MESSY_PARQUET}")
    print('='*50)
    print(f"parallel: Time of execution (Lazy loading to parquet) : {(end_local - start_local):.4f} seconds")
    print('='*50)
    


if __name__ == "__main__":
    for i in [1, 2, 3, 4, 5, 10]:
        i *= 1000000
        tracker = mt(interval=0.1)

        start = time.perf_counter()
        tracker.start()

        main(DF_LENGTH=i)

        end = time.perf_counter()
        generation_peak_kb = tracker.stop()

        print(f"parallel: Time of execution (Total): {(end - start):.4f} seconds")
        print(f"parallel: Time of execution (Total): {(generation_peak_kb):.8f} kb")
        print('='*50)
        print('\n\n\n\n')

    